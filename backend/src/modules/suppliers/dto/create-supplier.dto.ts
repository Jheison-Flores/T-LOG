import {
  IsBoolean,
  IsEmail,
  IsOptional,
  IsString,
  MaxLength,
} from 'class-validator';

export class CreateSupplierDto {
  // ============================================================
  // RAZÓN SOCIAL / NOMBRE
  // ============================================================

  @IsString()
  @MaxLength(150)
  name!: string;

  // ============================================================
  // RUC
  // ============================================================

  @IsOptional()
  @IsString()
  @MaxLength(20)
  ruc?: string;

  // ============================================================
  // DIRECCIÓN
  // ============================================================

  @IsOptional()
  @IsString()
  @MaxLength(255)
  address?: string;

  // ============================================================
  // TELÉFONO
  // ============================================================

  @IsOptional()
  @IsString()
  @MaxLength(50)
  phone?: string;

  // ============================================================
  // CORREO
  // ============================================================

  @IsOptional()
  @IsEmail()
  @MaxLength(120)
  email?: string;

  // ============================================================
  // ESTADO
  // ============================================================

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}
